#!/usr/bin/env python3
"""Sprint 2 performance evidence (BMS-NF-001, BMS-NF-002, BMS-NF-003).

Generates 10,000 accounts and 100,000 transaction lines, times start-up,
100 money operations and 100 mini statements, and writes the evidence to
docs/sprint2/perf-evidence.md.  Run with:  make perf
"""
import os
import platform
import subprocess
import sys
import time
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
ACC_FILE = os.path.join(DATA, "accounts.txt")
TXN_FILE = os.path.join(DATA, "transactions.txt")
DOCS = os.path.join(ROOT, "docs", "sprint2")
BANK = os.path.join(ROOT, "bank")

ACCOUNTS = 10000
TXN_LINES = 100000
PIN_HASH = "55f39b5145752c12"          # FNV-1a hash of the test PIN "4829"


def make_dataset():
    os.makedirs(DATA, exist_ok=True)
    with open(ACC_FILE, "w", encoding="utf-8") as fp:
        for i in range(ACCOUNTS):
            fp.write("%d,User%d,%s,100000.00,ACTIVE,0\n"
                     % (1001 + i, i, PIN_HASH))
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with open(TXN_FILE, "w", encoding="utf-8") as fp:
        for i in range(TXN_LINES):
            acc = 1001 + (i % ACCOUNTS)
            kind = "DEPOSIT" if i % 2 == 0 else "WITHDRAW"
            fp.write("%d,%d,%s,100.00,100000.00,%s\n"
                     % (i + 1, acc, kind, stamp))


def run_bank(text, timeout=180):
    started = time.perf_counter()
    proc = subprocess.run([BANK], input=text.encode(), stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, timeout=timeout)
    elapsed = time.perf_counter() - started
    return elapsed, proc.returncode, proc.stdout.decode("utf-8", "replace")


def main():
    subprocess.run(["make"], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)

    print("generating %d accounts and %d transaction lines..." % (ACCOUNTS, TXN_LINES))
    make_dataset()

    print("timing start-up (backup + integrity check + load)...")
    startup_s, rc, out = run_bank("0\n")
    startup_ok = rc == 0 and ("Loaded %d account(s)" % ACCOUNTS) in out

    print("timing 100 money operations (34 deposit, 33 withdraw, 33 balance)...")
    ops_input = ["1", "100"] * 34 + ["2", "100"] * 33 + ["3"] * 33
    ops_s, rc2, out2 = run_bank("1\n1001\n4829\n" + "\n".join(ops_input) + "\n0\n0\n")
    ops_ok = rc2 == 0 and "Login successful" in out2

    print("timing 100 mini statements...")
    mini_s, rc3, out3 = run_bank("1\n1001\n4829\n" + "4\n" * 100 + "0\n0\n")
    mini_ok = rc3 == 0 and "Balance for account" not in out3  # sanity: no crash

    avg_ops = ops_s / 100.0
    avg_mini = mini_s / 100.0

    rows = [
        ("Start-up: backup + integrity check + load %d accounts / %d log lines"
         % (ACCOUNTS, TXN_LINES), "%.3f s" % startup_s, "<= 2.00 s", "BMS-NF-002",
         startup_ok and startup_s <= 2.0),
        ("100 money operations (34 deposit, 33 withdraw, 33 balance), average",
         "%.4f s" % avg_ops, "<= 1.00 s", "BMS-NF-001", ops_ok and avg_ops <= 1.0),
        ("100 mini statements, average", "%.4f s" % avg_mini, "<= 1.00 s",
         "BMS-NF-003", mini_ok and avg_mini <= 1.0),
    ]

    os.makedirs(DOCS, exist_ok=True)
    lines = [
        "# Sprint 2 performance evidence",
        "",
        "Measured on **%s** with `%s`." % (
            platform.platform(),
            subprocess.getoutput("gcc --version").splitlines()[0]),
        "",
        "Dataset: **%d accounts**, **%d transaction lines**, generated by "
        "`tests/perf_test.py` (`make perf`)." % (ACCOUNTS, TXN_LINES),
        "",
        "| Measure | Result | SRS limit | Requirement | Status |",
        "|---|---|---|---|---|",
    ]
    for name, value, limit, req, ok in rows:
        lines.append("| %s | %s | %s | %s | %s |"
                     % (name, value, limit, req, "PASS" if ok else "FAIL"))
    lines += [
        "",
        "Reproduce with:",
        "",
        "```sh",
        "make clean",
        "make perf",
        "```",
        "",
        "The script prints this file and exits non-zero if any limit is missed.",
        "",
    ]
    with open(os.path.join(DOCS, "perf-evidence.md"), "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))

    all_ok = all(ok for _n, _v, _l, _r, ok in rows)
    print("| measure | result | limit | status |")
    for name, value, limit, _req, ok in rows:
        print("| %s | %s | %s | %s |" % (name, value, limit, "PASS" if ok else "FAIL"))
    print("evidence written to docs/sprint2/perf-evidence.md")
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
