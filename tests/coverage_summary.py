#!/usr/bin/env python3
import argparse
import gzip
import json
import os
import sys


def parse_gcov(path):
    stats = {}
    current = None
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            line = raw.strip()
            if line.startswith("file:"):
                current = line[5:]
                stats.setdefault(current, {
                    "lines": 0,
                    "covered_lines": 0,
                    "branches": 0,
                    "taken_branches": 0,
                })
            elif line.startswith("lcount:") and current is not None:
                parts = line.split(",")
                if len(parts) >= 2:
                    stats[current]["lines"] += 1
                    if int(parts[1]) > 0:
                        stats[current]["covered_lines"] += 1
            elif line.startswith("branch:") and current is not None:
                parts = line.split(",")
                if len(parts) >= 2:
                    stats[current]["branches"] += 1
                    if parts[1] == "taken":
                        stats[current]["taken_branches"] += 1
    return stats


def parse_gcov_json(path):
    stats = {}
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8", errors="replace") as handle:
        document = json.load(handle)

    for record in document.get("files", []):
        source = record.get("file") or document.get("data_file") or "unknown"
        item = stats.setdefault(source, {
            "lines": 0,
            "covered_lines": 0,
            "branches": 0,
            "taken_branches": 0,
        })
        for line in record.get("lines", []):
            item["lines"] += 1
            if (line.get("count") or 0) > 0:
                item["covered_lines"] += 1
            for branch in line.get("branches", []):
                item["branches"] += 1
                if (branch.get("count") or 0) > 0:
                    item["taken_branches"] += 1
    return stats


def collect(directory):
    merged = {}
    for entry in sorted(os.listdir(directory)):
        path = os.path.join(directory, entry)
        if not os.path.isfile(path):
            continue
        if entry.endswith(".gcov.json.gz") or entry.endswith(".gcov.json"):
            parsed = parse_gcov_json(path)
        elif entry.endswith(".gcov"):
            parsed = parse_gcov(path)
        else:
            continue
        for source, counts in parsed.items():
            target = merged.setdefault(source, {
                "lines": 0,
                "covered_lines": 0,
                "branches": 0,
                "taken_branches": 0,
            })
            for key in target:
                target[key] += counts[key]
    return merged


def percentage(part, whole):
    return 100.0 if whole == 0 else 100.0 * part / whole


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("directory")
    parser.add_argument("--output", required=True)
    parser.add_argument("--fail-under-lines", type=float, default=0.0)
    parser.add_argument("--fail-under-branches", type=float, default=0.0)
    args = parser.parse_args()

    stats = collect(args.directory)
    if not stats:
        print("No gcov data found in %s" % args.directory, file=sys.stderr)
        return 2

    totals = {
        "lines": sum(item["lines"] for item in stats.values()),
        "covered_lines": sum(item["covered_lines"] for item in stats.values()),
        "branches": sum(item["branches"] for item in stats.values()),
        "taken_branches": sum(item["taken_branches"] for item in stats.values()),
    }
    line_pct = percentage(totals["covered_lines"], totals["lines"])
    branch_pct = percentage(totals["taken_branches"], totals["branches"])

    rows = [
        "# Coverage summary",
        "",
        "| Source | Lines covered | Line coverage | Branches taken | Branch coverage |",
        "|---|---:|---:|---:|---:|",
    ]
    for source in sorted(stats, key=os.path.basename):
        item = stats[source]
        rows.append("| `%s` | %d/%d | %.2f%% | %d/%d | %.2f%% |" % (
            os.path.basename(source),
            item["covered_lines"], item["lines"],
            percentage(item["covered_lines"], item["lines"]),
            item["taken_branches"], item["branches"],
            percentage(item["taken_branches"], item["branches"]),
        ))
    rows += [
        "| **Total** | **%d/%d** | **%.2f%%** | **%d/%d** | **%.2f%%** |" % (
            totals["covered_lines"], totals["lines"], line_pct,
            totals["taken_branches"], totals["branches"], branch_pct,
        ),
        "",
        "Generated by `make coverage` from gcov line and branch data.",
        "",
    ]

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(rows))

    with open(os.path.join(os.path.dirname(args.output), "summary.json"), "w",
              encoding="utf-8") as handle:
        json.dump({
            "files": stats,
            "totals": totals,
            "line_coverage": line_pct,
            "branch_coverage": branch_pct,
        }, handle, indent=2)

    print("Line coverage: %.2f%% (%d/%d)" % (
        line_pct, totals["covered_lines"], totals["lines"]))
    print("Branch coverage: %.2f%% (%d/%d)" % (
        branch_pct, totals["taken_branches"], totals["branches"]))
    print("Report: %s" % args.output)

    if line_pct < args.fail_under_lines:
        print("Line coverage %.2f%% is below %.2f%%" % (
            line_pct, args.fail_under_lines), file=sys.stderr)
        return 1
    if branch_pct < args.fail_under_branches:
        print("Branch coverage %.2f%% is below %.2f%%" % (
            branch_pct, args.fail_under_branches), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
